// This file implements the canonical `hcl.canonical-document@1`
// materialization (RFC 0014 §9).
//
// Materialization consumes one validated `hcl.body@1` record and creates a
// new `hcl.native@1` or `hcl.tfvars@1` Document. It is not a formatter for
// an existing source: the input is the projected body record, the output
// is a new snapshot whose complete native model equals the promised input
// semantics (RFC 0014 §9).
//
// The style emits UTF-8 without BOM, LF line endings, two-space
// indentation per body nesting level, `name = value` attributes, block
// headers as `type "label" {`, and a trailing newline after the final
// item. The generated bytes are reparsed under the promised Profile and
// the reparsed native model is compared to the promised input semantics —
// numbers by canonical-decimal value equality, everything else by the
// structural equality of RFC 0014 §6. Failure returns no target Document,
// partial bytes, or partial provenance.

// Style identifier `hcl.canonical-document` (RFC 0014 §9).
const styleCanonical = "hcl.canonical-document"

// Sentinel attribute name of the standalone expression parse; any text
// that would parse into an additional body item is not one expression.
const sentinelAttribute = "expr"

// MaterializationFailureKind is the stable materialization failure
// category (consema-document materialization.rs; RFC 0014 §9).
type MaterializationFailureKind uint8

// The closed materialization failure categories.
const (
	// MaterializationFailureInvalidRequest: request or record fields are
	// contradictory or the record is not `hcl.body@1`.
	MaterializationFailureInvalidRequest MaterializationFailureKind = iota
	// MaterializationFailureUnsupportedProfile: the target profile is
	// unavailable.
	MaterializationFailureUnsupportedProfile
	// MaterializationFailureUnsupportedStyle: the target style is
	// unavailable for the profile.
	MaterializationFailureUnsupportedStyle
	// MaterializationFailureUnsupportedEncoding: the target encoding is
	// unsupported.
	MaterializationFailureUnsupportedEncoding
	// MaterializationFailureUnsupportedNewline: the target style does not
	// support the newline policy.
	MaterializationFailureUnsupportedNewline
	// MaterializationFailureUnrepresentable: a portable input cannot be
	// represented by the target profile (the tfvars block restriction,
	// invalid identifiers, duplicate attributes, non-finite reals).
	MaterializationFailureUnrepresentable
	// MaterializationFailureResourceLimit: a configured bound was reached;
	// output is not truncated to success.
	MaterializationFailureResourceLimit
	// MaterializationFailureFormationFailed: the generated bytes did not
	// form the required target document, or the reparse closure failed.
	MaterializationFailureFormationFailed
)

// MaterializationFailure is the typed materialization failure. It
// implements error and the RFC 0016 §6 Code() contract with the frozen
// registered codes.
type MaterializationFailure struct {
	// Kind identifies the failure.
	Kind MaterializationFailureKind
	// Detail is the stable detail of InvalidRequest.
	Detail string
	// Path is the offending input location of Unrepresentable.
	Path protocol.ValuePath
	// ValueKind is the offending PortableValue kind of Unrepresentable.
	ValueKind core.Kind
	// LimitName is the stable limit name of a ResourceLimit.
	LimitName string
}

// Error implements error.
func (e *MaterializationFailure) Error() string {
	switch e.Kind {
	case MaterializationFailureInvalidRequest:
		return "hcl: materialization request is invalid: " + e.Detail
	case MaterializationFailureUnsupportedProfile:
		return "hcl: materialization profile is unavailable"
	case MaterializationFailureUnsupportedStyle:
		return "hcl: materialization style is unavailable for the profile"
	case MaterializationFailureUnsupportedEncoding:
		return "hcl: materialization encoding is unsupported"
	case MaterializationFailureUnsupportedNewline:
		return "hcl: materialization newline policy is unsupported by the style"
	case MaterializationFailureUnrepresentable:
		return "hcl: portable kind " + e.ValueKind.String() + " is not representable"
	case MaterializationFailureResourceLimit:
		return "hcl: materialization limit " + e.LimitName + " reached"
	case MaterializationFailureFormationFailed:
		return "hcl: generated bytes did not form the target document"
	}
	return "hcl: materialization failure"
}

// Code returns the frozen registered code for the failure (RFC 0014 §9,
// §11). InvalidRequest keeps the runner-facing `invalid-record` spelling
// through Detail; the Code here follows the shared-core mapping.
func (e *MaterializationFailure) Code() string {
	switch e.Kind {
	case MaterializationFailureInvalidRequest:
		return "core.materialization.invalid-request@1"
	case MaterializationFailureUnsupportedProfile:
		return "core.materialization.unsupported-profile@1"
	case MaterializationFailureUnsupportedStyle:
		return "core.materialization.unsupported-style@1"
	case MaterializationFailureUnsupportedEncoding:
		return "core.materialization.unsupported-encoding@1"
	case MaterializationFailureUnsupportedNewline:
		return "core.materialization.unsupported-newline@1"
	case MaterializationFailureUnrepresentable:
		return "hcl.materialization.unrepresentable@1"
	case MaterializationFailureResourceLimit:
		return "hcl.materialization.resource-limit@1"
	case MaterializationFailureFormationFailed:
		return "core.materialization.formation-failed@1"
	}
	return "core.materialization.formation-failed@1"
}

// MaterializationFidelity is the closed materialization fidelity
// (consema-document materialization.rs).
type MaterializationFidelity uint8

// The two frozen fidelity classes.
const (
	// MaterializationFidelityExact means every input fact round-trips
	// through the target's exact projection contract.
	MaterializationFidelityExact MaterializationFidelity = iota
	// MaterializationFidelityTransformed means complete semantics survive
	// an explicit reversible re-encoding.
	MaterializationFidelityTransformed
)

// String returns the stable fidelity name.
func (f MaterializationFidelity) String() string {
	switch f {
	case MaterializationFidelityExact:
		return "Exact"
	case MaterializationFidelityTransformed:
		return "Transformed"
	}
	return "Exact"
}

