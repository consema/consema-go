package xml

// This file implements canonical `xml.safe-canonical-document@1`
// materialization (RFC 0012 §10; consema-rs/consema-xml/src/materialization.rs).
// The style consumes one fully validated `xml.element-tree@1` value and
// creates a new `xml.1.0-safe@1` Document. It is not W3C Canonical XML and
// does not claim C14N equivalence. The style deterministically chooses
// declaration spelling, double-quoted attributes, generated namespace
// prefixes, first-use namespace declaration placement, empty-element
// spelling, reference spelling, and the requested LF/CRLF final newline.
//
// UTF-8, UTF-16LE, and UTF-16BE output are supported under the source
// rules; UTF-16 output always carries its BOM. The complete tree is
// validated before generation, the exact generated bytes are reparsed
// under the promised Profile and encoding, and the reparsed native tree is
// compared to the promised input semantics. Failure returns no target
// Document and no partial output bytes.

import (
	"strings"

	"consema.dev/consema/core"
	"consema.dev/consema/document"
	"consema.dev/consema/protocol"
)

// MaterializationFailureKind is the stable materialization failure
// category (consema-document materialization.rs).
type MaterializationFailureKind uint8

// The closed materialization failure categories.
const (
	// MaterializationFailureInvalidRequest: request fields or input records
	// are contradictory.
	MaterializationFailureInvalidRequest MaterializationFailureKind = iota
	// MaterializationFailureUnsupportedProfile: the target profile is
	// unavailable.
	MaterializationFailureUnsupportedProfile
	// MaterializationFailureUnsupportedStyle: the target style is
	// unavailable for the profile.
	MaterializationFailureUnsupportedStyle
	// MaterializationFailureUnsupportedEncoding: the target encoding is
	// unsupported.
	MaterializationFailureUnsupportedEncoding
	// MaterializationFailureUnsupportedNewline: the target style does not
	// support the newline policy.
	MaterializationFailureUnsupportedNewline
	// MaterializationFailureUnrepresentable: a portable input cannot be
	// represented by the target profile.
	MaterializationFailureUnrepresentable
	// MaterializationFailureResourceLimit: a configured bound was reached;
	// output is not truncated to success.
	MaterializationFailureResourceLimit
	// MaterializationFailureFormationFailed: the generated bytes did not
	// form the required target document.
	MaterializationFailureFormationFailed
)

// MaterializationFailure is the typed materialization failure. It
// implements error and the RFC 0016 §6 Code() contract with the frozen
// registered codes.
type MaterializationFailure struct {
	// Kind identifies the failure.
	Kind MaterializationFailureKind
	// Path is the offending input location of Unrepresentable.
	Path protocol.ValuePath
	// ValueKind is the offending PortableValue kind of Unrepresentable.
	ValueKind core.Kind
	// LimitName is the stable limit name of a ResourceLimit.
	LimitName string
	// Reason is the admission reason of InvalidRequest.
	Reason string
}

// Error implements error.
func (e *MaterializationFailure) Error() string {
	switch e.Kind {
	case MaterializationFailureInvalidRequest:
		return "xml: materialization request is invalid: " + e.Reason
	case MaterializationFailureUnsupportedProfile:
		return "xml: materialization profile is unavailable"
	case MaterializationFailureUnsupportedStyle:
		return "xml: materialization style is unavailable for the profile"
	case MaterializationFailureUnsupportedEncoding:
		return "xml: materialization encoding is unsupported"
	case MaterializationFailureUnsupportedNewline:
		return "xml: materialization newline policy is unsupported by the style"
	case MaterializationFailureUnrepresentable:
		return "xml: portable kind " + e.ValueKind.String() + " is not representable"
	case MaterializationFailureResourceLimit:
		return "xml: materialization limit " + e.LimitName + " reached"
	case MaterializationFailureFormationFailed:
		return "xml: generated bytes did not form the target document"
	}
	return "xml: materialization failure"
}

// Code returns the frozen registered code for the failure.
func (e *MaterializationFailure) Code() string {
	switch e.Kind {
	case MaterializationFailureInvalidRequest:
		return "core.materialization.invalid-request@1"
	case MaterializationFailureUnsupportedProfile:
		return "core.materialization.unsupported-profile@1"
	case MaterializationFailureUnsupportedStyle:
		return "core.materialization.unsupported-style@1"
	case MaterializationFailureUnsupportedEncoding:
		return "core.materialization.unsupported-encoding@1"
	case MaterializationFailureUnsupportedNewline:
		return "core.materialization.unsupported-newline@1"
	case MaterializationFailureUnrepresentable:
		return "core.materialization.unrepresentable@1"
	case MaterializationFailureResourceLimit:
		return "core.materialization.resource-limit@1"
	case MaterializationFailureFormationFailed:
		return "core.materialization.formation-failed@1"
	}
	return "core.materialization.formation-failed@1"
}

