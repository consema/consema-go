import (
	"bytes"
	"context"
	"testing"
)

// parseFixture is a representative `hcl.native@1` document (~1.5 KiB).
var parseFixture = []byte(`# consema.tf
terraform {
  required_version = ">= 1.5"
}

variable "region" {
  type    = string
  default = "eu-west-1"
}

locals {
  name     = "consema-service"
  version  = "0.19.0"
  replicas = 3
  enabled  = true
  ratio    = 0.875
  labels = {
    env    = "production"
    team   = "platform"
    region = var.region
  }
}

resource "consema_deployment" "web" {
  name             = local.name
  replicas         = local.replicas
  strategy         = "rolling-update"
  max_surge        = "25%"
  max_unavailable  = 0
  resources        = { cpu = "500m", memory = "128Mi" }
  endpoint         = [for i in range(3) : "/api/v${i}"]
  annotation       = <<EOT
中文 配置 🦀 emoji
generated by consema ${local.version}
EOT
  health_check = {
    path     = "/health"
    interval = "30s"
    timeout  = "10s"
    retries  = 3
  }
}

output "endpoints" {
  value = consema_deployment.web.endpoint
}
`)

// benchSink keeps benchmark results alive so the compiler cannot elide the
// measured work.
var benchSink []byte

// BenchmarkParse measures one full native HCL parse of the fixture under
// the production default limits.
func BenchmarkParse(b *testing.B) {
	b.SetBytes(int64(len(parseFixture)))
	b.ReportAllocs()
	for i := 0; i < b.N; i++ {
		doc, failure := Parse(context.Background(), parseFixture, HclProfileNativeV1,
			HclEncodingSelectionProfileDefault(), DefaultHclParseLimits())
		if failure != nil {
			b.Fatalf("parse: %v", failure)
		}
		benchSink = doc.Render()
	}
}

// BenchmarkRender measures the lossless render closure.
func BenchmarkRender(b *testing.B) {
	doc, failure := Parse(context.Background(), parseFixture, HclProfileNativeV1,
		HclEncodingSelectionProfileDefault(), DefaultHclParseLimits())
	if failure != nil {
		b.Fatalf("parse: %v", failure)
	}
	b.SetBytes(int64(len(parseFixture)))
	b.ReportAllocs()
	for i := 0; i < b.N; i++ {
		benchSink = doc.Render()
		if !bytes.Equal(benchSink, parseFixture) {
			b.Fatal("render closure violated")
		}
	}
}
